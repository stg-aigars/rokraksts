// Rakstīto burtu (latviešu skolas raksta) shematiskās formas blāvajam paraugam: mūsu pašu
// līknes pēc vispārzināmā rakstītā raksta kanona, nevis kāda attēla kopija. Fonta vienībās tāpat
// kā scripts/letter-shapes.mjs (pamatlīnija 0, mazo burtu augstums 450, lielo 700, apakšējā −250).
// Mazajiem burtiem ir izejas vilciens pa labi uz augšu (savienojumam ar nākamo burtu).
// Cipariem un pieturzīmēm rakstītās formas nav: tur paraugs paliek drukātais.
//
// Zīmes: garumzīme, jumtiņš un komats kā drukātajiem; Ģ un ģ rakstītajā rakstā zīme ir augšā
// (jumtiņam līdzīga), kā skolas paraugos (īpašnieka lēmums 4. posmā).

import { dot, join, line } from './letter-shapes.mjs'

/** Gluda līkne caur dotajiem punktiem (Catmull–Rom), kā blīva punktu virkne. */
export function cr(...points) {
  const out = []
  const at = (i) => points[Math.max(0, Math.min(points.length - 1, i))]
  for (let i = 0; i < points.length - 1; i++) {
    const [p0, p1, p2, p3] = [at(i - 1), at(i), at(i + 1), at(i + 2)]
    const steps = Math.max(8, Math.ceil(Math.hypot(p2[0] - p1[0], p2[1] - p1[1]) / 4))
    for (let s = i === 0 ? 0 : 1; s <= steps; s++) {
      const t = s / steps
      const t2 = t * t
      const t3 = t2 * t
      out.push(
        [0, 1].map(
          (k) =>
            0.5 *
            (2 * p1[k] +
              (-p0[k] + p2[k]) * t +
              (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * t2 +
              (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * t3),
        ),
      )
    }
  }
  return out
}

